# Database
# 讀 DATABASE_URL 環境變數（正式環境指向 PostgreSQL），沒設定時退回 SQLite——
# 本機開發、CI 完全不受影響，維持原本零設定即可跑的行為。後台管理系統的
# 讀寫（公告、稽核日誌等）需要能撐過容器重啟/重新部署，Render/Cloud Run
# 的檔案系統是暫時性的，SQLite 檔案在那些平台上撐不住這個需求，這也是
# 這個專案原本的 README 就已經寫著「生產環境請切換至 PostgreSQL」的原因。
_database_url = os.getenv("DATABASE_URL")
if _database_url:
    # Render/Cloud Run 這類受管平台的 Postgres 連線一律要求 TLS，但本機/區網
    # 的 Postgres（例如開發機上直接裝的 PostgreSQL 服務）預設沒有啟用 SSL，
    # 強制 ssl_require=True 連線會直接被拒絕。用連線字串裡的 host 自動判斷是
    # 本機還是遠端，不用另外設一個環境變數區分「本機 Postgres」與「正式環境
    # Postgres」這兩種情境。
    _db_host = urlparse(_database_url).hostname
    DATABASES = {
        "default": dj_database_url.parse(
            _database_url,
            conn_max_age=600,
            ssl_require=_db_host not in ("localhost", "127.0.0.1", "::1"),
        )
    }
else:
    # REQUIRE_DATABASE_URL：選擇性的嚴格模式（docker-compose.prod.yml 會開啟）。
    # 正式環境是多個 gunicorn worker、容器檔案系統是暫時性的；DATABASE_URL 漏設時
    # 若靜默退回 SQLite，會進入多 worker 寫入鎖競爭，而且資料只存在容器內，重建
    # 容器就消失。開啟後直接啟動失敗，讓設定錯誤在部署當下就被發現。預設不開，
    # 本機開發與 CI 維持零設定就能跑 SQLite 的行為。
    if os.getenv("REQUIRE_DATABASE_URL", "").lower() in ("1", "true", "yes"):
        raise ImproperlyConfigured(
            "REQUIRE_DATABASE_URL 已開啟，但 DATABASE_URL 未設定。"
            "請在 .env 填入 PostgreSQL 連線字串，否則會退回不會持久化的 SQLite。"
        )
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }

